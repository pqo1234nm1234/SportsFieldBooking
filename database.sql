-- RLS
alter table public.profiles enable row level security;
alter table public.sports_fields enable row level security;
alter table public.bookings enable row level security;
alter table public.payments enable row level security;

drop policy if exists "profiles own select" on public.profiles;
create policy "profiles own select" on public.profiles for select to authenticated using (id=auth.uid());

drop policy if exists "profiles own update" on public.profiles;
create policy "profiles own update" on public.profiles for update to authenticated using (id=auth.uid());

drop policy if exists "fields authenticated read" on public.sports_fields;
create policy "fields authenticated read" on public.sports_fields for select to authenticated using (true);

drop policy if exists "bookings own read" on public.bookings;
create policy "bookings own read" on public.bookings for select to authenticated using (customer_id=auth.uid());

drop policy if exists "bookings own insert" on public.bookings;
create policy "bookings own insert" on public.bookings for insert to authenticated with check (customer_id=auth.uid());

drop policy if exists "bookings own update" on public.bookings;
create policy "bookings own update" on public.bookings for update to authenticated using (customer_id=auth.uid()) with check (customer_id=auth.uid());

drop policy if exists "payments own read" on public.payments;
create policy "payments own read" on public.payments for select to authenticated
using (exists(select 1 from public.bookings b where b.booking_id=payments.booking_id and b.customer_id=auth.uid()));

drop policy if exists "payments own insert" on public.payments;
create policy "payments own insert" on public.payments for insert to authenticated
with check (exists(select 1 from public.bookings b where b.booking_id=payments.booking_id and b.customer_id=auth.uid()));

